places_travel = ['morocco', 'dubai', 'japan', 'italy', 'greece']
print(f'This is where I would love to visit: {places_travel}')

print(sorted(places_travel))

print(places_travel)

places_travel.reverse()
print(places_travel)

places_travel.reverse()
print(f'Back to original order: {places_travel}')

places_travel.sort()
print(places_travel)

places_travel.sort(reverse=True)
print(places_travel)

print(f'These are the top {len(places_travel)} places I want to visit!')


